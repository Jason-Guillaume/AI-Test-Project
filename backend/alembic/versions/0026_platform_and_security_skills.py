def _seed_skills(bind, skills, revisions):
    for key, name, description, body in _SKILLS:
        content = f"{body.strip()}\n\n{_PLATFORM_BOUNDARY.strip()}"
        if key.startswith("c200"):
            content += f"\n\n{_SECURITY_BOUNDARY.strip()}"
        skill_id = bind.execute(
            sa.select(skills.c.id).where(skills.c.key == key),
        ).scalar_one_or_none()
        if skill_id is None:
            bind.execute(skills.insert().values(
                key=key,
                name=name,
                description=description,
                content=content,
                is_enabled=True,
                version=1,
            ))
            skill_id = bind.execute(
                sa.select(skills.c.id).where(skills.c.key == key),
            ).scalar_one()

        revision_exists = bind.execute(
            sa.select(revisions.c.skill_definition_id).where(
                revisions.c.skill_definition_id == skill_id,
                revisions.c.version == 1,
            ),
        ).first()
        if revision_exists is None:
            bind.execute(revisions.insert().values(
                skill_definition_id=skill_id,
                version=1,
                snapshot_json={
                    "name": name,
                    "description": description,
                    "content": content,
                    "is_enabled": True,
                },
            ))


