"""图形验证码模块。

用途：注册接口在提交前要求完成一次图形验证码校验，用于阻止自动化脚本批量注册账号。

实现要点：
- 图片由 Pillow 渲染，字符集排除易混淆字符（0/O/1/I/l）；每字符独立旋转与抖动，
  叠加干扰线与噪声点降低 OCR 识别率
- 校验码与图片绑定一个 UUID4 challenge_id，写入进程内 dict + threading.Lock
- 校验通过即删除：一次性使用，防止同一 challenge 被暴力重放
- 过期条目在每次签发时机会式清理，不做后台定时任务

已知限制（**必须显式声明**）：
- **单进程内存存储**：challenge 仅保存在本进程内存中，重启即失效；
  多 worker / 多实例部署必须切换到 Redis 或 DB 后端，本模块不做分布式一致性
- **不做持久化**：进程退出时 challenge 全部丢失，跨重启的注册请求会失败，
  用户需要重新拉一张验证码
- **不做用户级限流**：签发速率只按 IP 维度限流（详见 app.shared.rate_limit）；
  单 IP 内的用户级防滥用依赖网关侧策略
"""
